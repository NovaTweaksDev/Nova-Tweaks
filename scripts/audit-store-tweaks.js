const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const policy = require('../electron/services/tweaks/storeTweakPolicy.json');
const signals = [
  ['BCD', /\bbcdedit\b/i],
  ['Windows Update service/cache', /\bwuauserv\b|SoftwareDistribution/i],
  ['Services', /Stop-Service|Set-Service|sc\.exe/i],
  ['Machine registry', /HKLM:|HKEY_LOCAL_MACHINE/i],
  ['Native API / driver', /DllImport|NtSetTimerResolution|DeviceIoControl/i],
  ['Processes', /Stop-Process|ProcessPriority|Affinity/i],
  ['File deletion', /Remove-Item/i]
];
function auditTweaks() {
  return fs.readdirSync(path.join(root, 'resources/tweaks/configs')).filter((name) => name.endsWith('.json')).sort().map((name) => {
    const configBytes = fs.readFileSync(path.join(root, 'resources/tweaks/configs', name));
    const config = JSON.parse(configBytes);
    const scriptRoot = path.join(root, 'resources/tweaks/scripts', config.id);
    const scripts = fs.readdirSync(scriptRoot).filter((file) => file.endsWith('.ps1')).sort();
    if (!scripts.length || config.id !== name.slice(0, -5)) throw new Error('Tweak source/identity missing.');
    const content = scripts.map((file) => fs.readFileSync(path.join(scriptRoot, file), 'utf8').replace(/\r\n/g, '\n')).join('\n');
    const detected = signals.filter(([, expression]) => expression.test(content)).map(([label]) => label);
    const reason = policy.exclusions[config.id];
    const classification = ['disable_nx_dep', 'ignore_all_boot_failures'].includes(config.id)
      ? 'Explicit safety-policy conflict (10.2)'
      : reason || detected.length || config.risk_level === 'high'
        ? 'Certification risk; review 10.2 / 10.2.8'
        : 'No specific policy conflict identified by static review';
    return {
      id: config.id, name: config.name, risk: config.risk_level || 'unspecified',
      classification, store: reason ? 'Excluded' : 'Retained pending certification',
      reason: reason || 'User consent and supported methods require feature-level verification; no blanket prohibition inferred.',
      operations: detected, technicalDetails: config.technical_details,
      sourceSha256: crypto.createHash('sha256').update(configBytes.toString().replace(/\r\n/g, '\n')).update(content).digest('hex'),
      scripts: scripts.map((file) => `resources/tweaks/scripts/${config.id}/${file}`)
    };
  });
}
function renderAudit() {
  const rows = auditTweaks();
  const clean = (value) => String(value || '').replace(/\|/g, '/').replace(/[\r\n]+/g, ' ');
  return [
    '# Store tweak review',
    '',
    'Static review of every bundled definition and its PowerShell files. Generated by scripts/audit-store-tweaks.js.',
    'Policy source: https://learn.microsoft.com/en-us/windows/apps/publish/store-policies (7.20, reviewed 2026-10-12).',
    'Operation signals are conservative source matches, including detection/restore paths and comments; they do not prove a prohibited apply action.',
    'Retained means no packaging exclusion, not Microsoft approval or confirmed safety. Registry writes and BCD changes are not categorically prohibited.',
    'DEP and boot-recovery disabling conflict with 10.2 safeguards. Hypervisor disabling is conservatively excluded because it may prevent VBS, rather than claiming an explicit Hyper-V ban.',
    '',
    '| ID | Risk | Classification | Store | Source operations | Technical behavior |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row.id} | ${clean(row.risk)} | ${row.classification} | ${row.store} | ${row.operations.join(', ') || 'No flagged operation'} | ${clean(row.technicalDetails)} |`),
    '',
    'Snapshot identifiers (configuration + all primary PowerShell sources):',
    '',
    ...rows.map((row) => `- ${row.id}: ${row.sourceSha256}`),
    ''
  ].join('\n');
}
if (require.main === module) {
  const output = path.join(root, 'docs/STORE_TWEAK_REVIEW.md');
  const report = renderAudit();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== report) throw new Error('Store tweak review is stale. Regenerate and review changed operations.');
  } else fs.writeFileSync(output, report);
}
module.exports = { auditTweaks, renderAudit };
